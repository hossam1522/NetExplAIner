"""All prompts used by NetExplAIner, in a single place.

The text (including the leading whitespace of continuation lines and trailing
spaces) is exactly what was sent to the models in the paper experiments.
Do NOT reformat these strings: ``tests/test_prompts.py`` checks their hashes.
"""

# Decomposition step: question q -> sub-questions {q_1, ..., q_k}.
# (Written with explicit "\n" because the second line ends with a space that
# editors tend to strip.)
DECOMPOSITION = (
    "You are a network analyst that generates multiple sub-questions related to an input question about a network trace provided in text format.\n"
    "        I do not need the answer to the question. The ouput should only contain the sub-questions. Be as simple as possible. \n"
    "        3 sub-questions as maximum. The sub-questions cannot answer directly the input question.\n"
    "        Input question: {question}"
)

# Answering step over the trace. Used for each sub-question q_i and, in the
# direct strategy, for the original question.
ANSWER = """You are a network analyst that answer questions about network traces.
        Use the following network trace to answer the questions.
        DON'T GIVE FUNCTIONS OR CODE, ONLY THE ANSWER.
        Question: "{question}"
        Trace:
        {traces}"""

# Aggregation function g: a = g(q, {(q_i, a_i)}). Synthesizes the final answer
# from the question and the (sub-question, answer) pairs. The trace is NOT
# included: the final answer must come from the intermediate answers.
AGGREGATION = """DO NOT GIVE FUNCTIONS OR CODE, ONLY THE ANSWER.
        Here is a set of Q+A pairs:
        {context}
        Use these to synthesize an answer to the question: {question}"""

# Chain-of-thought baseline (not part of the original paper experiments):
# same as ANSWER but asking for step-by-step reasoning before the answer.
COT = """You are a network analyst that answer questions about network traces.
        Use the following network trace to answer the questions.
        DON'T GIVE FUNCTIONS OR CODE.
        Think step by step and then give the final answer.
        Question: "{question}"
        Trace:
        {traces}"""

# LLM judge: similarity (0-100) between generated and reference sub-questions.
JUDGE_SUBQUESTIONS = """Here is a question and the subquestions that were generated by LLM:
        Question: "{question}"
        Subquestions: "{subquestions_LLM}"
        Compare these to the subquestions that were provided:
        "{subquestions}"
        Are the subquestions generated by the LLM similar to the subquestions provided?
        You ONLY can answer with a number, indicating the percentage of similarity."""

# LLM judge: YES/NO correctness of the final answer against the ground truth.
JUDGE_ANSWER = """Here is a question and the answer that was generated by LLM:
        Question: "{question}"
        Answer LLM: "{answer_LLM}"
        Compare it with the answer that was provided:
        "{answer}"
        Is the answer generated by the LLM almost correct compared to the answer provided?
        You ONLY can answer YES/NO"""


def format_qa_pairs(questions: list, answers: list) -> str:
    """Render (sub-question, answer) pairs as the ``{context}`` of AGGREGATION."""
    formatted_string = ""
    for i, (question, answer) in enumerate(zip(questions, answers), start=1):
        formatted_string += f"Question {i}: {question}\nAnswer {i}: {answer}\n\n"
    return formatted_string.strip()
